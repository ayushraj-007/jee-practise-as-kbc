export function getClientVaultQuestions(topic: string): QuizQuestion[] {
  const t = (topic || '').toLowerCase();
  if (t.includes('physics')) return clientPhysicsVault;
  if (t.includes('chemistry')) return clientChemistryVault;
  if (t.includes('math')) return clientMathsVault;

  // Mixed PCM Vault: blend 5 Physics, 5 Chemistry, 5 Maths, 1 Grand Milestone
  return [
    clientPhysicsVault[0], clientChemistryVault[0], clientMathsVault[0], clientPhysicsVault[1], clientChemistryVault[1], // 1-5 Basic
    clientMathsVault[5], clientPhysicsVault[5], clientChemistryVault[5], clientMathsVault[6], clientPhysicsVault[6],     // 6-10 Inter
    clientChemistryVault[10], clientMathsVault[10], clientPhysicsVault[10], clientChemistryVault[11],              // 11-14 Adv
    clientMathsVault[14],                                                                                         // 15 Crore
    clientPhysicsVault[14],                                                                                       // 16 Spare
  ];
}

export function generateClientWeakAnalysis(
  results: QuestionSessionResult[],
  topic: string
): WeakTopicReport {
  const total = results.length;
  const correct = results.filter((r) => r.isCorrect).length;
  const incorrect = results.filter((r) => !r.isCorrect);

  const mastered = Array.from(
    new Set(results.filter((r) => r.isCorrect).map((r) => r.topicTag || 'Core Concept'))
  ).slice(0, 3);

  const weakTopics = incorrect.map((r) => ({
    topic: r.topicTag || 'Key Concept',
    mistakeReason: `Chose alternate option under time pressure on "${r.question.slice(0, 45)}...".`,
    revisionTip: 'Review standard NCERT definitions and solve 5 speed PYQs on this exact formula pattern.',
    formula: r.explanation ? r.explanation.slice(0, 90) : 'Review core formula derivation',
  })).slice(0, 4);

  const scorePct = total > 0 ? Math.round((correct / total) * 100) : 0;

  return {
    overallScore: scorePct,
    correctCount: correct,
    totalQuestions: total,
    masteredTopics: mastered,
    weakTopics,
    hostVerdict:
      scorePct >= 70
        ? 'Adbhut pradarshan! Thoda sa revision aur aap agle pradarshan me shandar jeet darj karenge!'
        : 'Afsos, par haar ke aage hi jeet hai! In chune hue sutron ka abhyas kijiye aur aage badhiye!',
  };
}
